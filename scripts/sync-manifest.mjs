// Writes the tools array of manifest.json from src/tools/catalog.ts so the two cannot drift. Run by `npm run build`.
import fs from 'node:fs';
import { TOOLS } from '../src/tools/catalog.ts';
const m = JSON.parse(fs.readFileSync('manifest.json', 'utf8'));
m.tools = TOOLS.map((t) => ({ name: t.name, displayName: t.displayName, description: t.description, parametersSchema: t.parametersSchema }));
fs.writeFileSync('manifest.json', JSON.stringify(m, null, 2) + '\n');
console.log(`manifest tools synced: ${m.tools.length}`);
// Embed the stdio MCP server so the worker can install it next to each opencode agent's config.
fs.writeFileSync('src/mcp-source.ts', `// GENERATED by scripts/sync-manifest.mjs from scripts/ado-mcp.mjs. Do not edit.\nexport const MCP_SOURCE: string = ${JSON.stringify(fs.readFileSync('scripts/ado-mcp.mjs', 'utf8'))};\n`);
